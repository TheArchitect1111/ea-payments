import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = process.cwd();
const json = JSON.parse(fs.readFileSync(path.join(root, 'lib/cigar-ctp/questions.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'lib/cigar-ctp/engine.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true }, reportDiagnostics: true });
assert.equal((compiled.diagnostics ?? []).length, 0, 'Engine TypeScript syntax must compile');
const mod = { exports: {} };
new Function('require', 'module', 'exports', compiled.outputText)(id => id === './questions.json' ? json : require(id), mod, mod.exports);
const e = mod.exports;
assert.equal(json.questions.length, 30, 'Approved three-path question bank');
for (const [role, prefix] of [['brand', 'B'], ['lounge', 'L'], ['distributor', 'D']]) {
  const answers = { C01: { selected: [role], detail: '' } };
  const questions = e.visibleCigarQuestions(answers);
  assert.equal(questions.filter(q => q.id.startsWith(prefix)).length, 7, `${role} must have seven targeted questions`);
  assert.equal(questions.length, 16, `${role} includes seven shared and two closing questions`);
  assert.equal(questions.filter(q => ['B', 'L', 'D'].some(p => q.id.startsWith(p)) && !q.id.startsWith(prefix)).length, 0, 'No unrelated roles');
  assert.equal(e.primaryRole(answers), role);
}
assert.equal(e.visibleCigarQuestions({}).length, 9, 'Unclear role keeps guided core and close');
assert.ok(json.questions.every(q => q.detailsPrompt && q.options.some(o => o.id === 'other') && q.options.some(o => o.id === 'unsure')), 'Every choice screen must offer Other, Unsure, and detail invitation');
const q = e.CIGAR_QUESTIONS.find(q => q.id === 'C04');
let answer = e.updateCigarChoice(q, undefined, 'data_entry');
answer = e.updateCigarChoice(q, { ...answer, detail: 'About five hours every week, not verified.' }, 'other');
assert.deepEqual(answer.selected, ['data_entry', 'other'], 'Other must coexist with preselected response');
assert.match(answer.detail, /five hours/, 'Adding Other must not erase the detail');
answer = e.updateCigarChoice(q, answer, 'unsure');
assert.deepEqual(answer.selected, ['unsure'], 'Unsure must exclude contradictory selections');
const unknown = e.buildCigarPreview({ C01: { selected: ['lounge'], detail: '' } });
assert.equal(unknown.financialStatus, 'not-quantified');
assert.equal(unknown.findings.length, 0);
const reporting = e.buildCigarPreview({ C01: { selected: ['brand'], detail: '' }, B03: { selected: ['asked'], detail: 'Two weeks late' } });
assert.ok(reporting.findings.some(f => /report/i.test(f.title)), 'Delayed brand statements must trigger report tracking');
assert.equal(reporting.financialStatus, 'not-quantified', 'Narrative numbers must not mint financial estimates');
const ui = fs.readFileSync(path.join(root, 'app/discover/cigar/CigarJourney.tsx'), 'utf8');
const route = fs.readFileSync(path.join(root, 'app/discover/cigar/page.tsx'), 'utf8');
assert.match(ui, /type="file"/);
assert.match(ui, /No customer submissions or emails are sent/);
assert.match(ui, /Submit Assessment/);
assert.match(ui, /Your Cigar Business Capacity Assessment has been received/);
assert.match(ui, /Please check your email/);
assert.match(ui, /cigarStepImage/);
assert.match(ui, /\/api\/cigar-ctp\/preview\/submit/);
assert.match(ui, /sessionStorage/);
assert.match(ui, /This assessment will take 5–8 minutes/);
assert.match(ui, /window\.scrollTo\(\{ top: 0, left: 0, behavior: 'instant' \}\)/, 'New question must automatically reset page to top');
assert.ok(!ui.includes('Photography matched to the current assessment topic'), 'Removed image filler must stay absent');
assert.match(ui, /CLARITY · CAPACITY · CONFIDENCE/, 'Upper-left motto visible on every screen');
assert.match(ui, /CIGAR_INTRO_IMAGE_TITLE/, 'Introduction image uses its original heading');
assert.ok(ui.includes('visualCopy?.title'), 'Image title must change with each question');
assert.ok(ui.includes('visualCopy?.reason'), 'Question-specific why-this-matters sentence must render');
assert.ok(ui.includes('bg-gradient-to-b from-black/40 via-transparent to-black/50'), 'Subtle image gradient must preserve readable titles');
assert.ok(ui.includes('object-contain object-center'), 'Complete heads, faces and bodies must remain visible');
const visualCopy = fs.readFileSync(path.join(root, 'lib/cigar-ctp/visual-copy.ts'), 'utf8');
assert.ok(visualCopy.includes('A clearer picture at every step.'), 'Original introductory title must be restored');
for (const q of json.questions) {
  assert.ok(visualCopy.includes('  ' + q.id + ': { title: '), q.id + ' must have an individual title and reason');
}
const editorialSource = fs.readFileSync(path.join(root, 'lib/cigar-ctp/editorial-images.ts'), 'utf8');
const editorialJson = editorialSource.split('export const CIGAR_EDITORIAL_IMAGES = ')[1]?.split(' as const;')[0];
assert.ok(editorialJson, 'Editorial images must be available');
const images = JSON.parse(editorialJson);
assert.equal(Object.keys(images).length, 35, '30 question photos, intro and four supporting stages');
const photoIds = Object.values(images).map(image => new URL(image.src).pathname);
assert.equal(new Set(photoIds).size, 35, 'Every CTP screen must have a distinct image file, not a repeated URL or crop');
for (const q of json.questions) assert.ok(images[q.id]?.src && images[q.id]?.alt, 'Photo and appropriate alt for ' + q.id);
assert.ok(!ui.includes('Photography matched to the current assessment topic'), 'No restored filler subtitle');
const discoveryLayout=fs.readFileSync(path.join(root,'app/discover/layout.tsx'),'utf8');
const discoverGuide=fs.readFileSync(path.join(root,'app/discover/DiscoverGuide.tsx'),'utf8');
assert.match(discoveryLayout,/DiscoverGuide/, 'Shared discover layout must use route-aware EA Guide');
assert.match(discoverGuide,/pathname\.startsWith\('\/discover\/cigar\/'\)/, 'Guide must be disabled only for cigar questionnaire');
assert.match(discoverGuide,/return null/, 'No orb or helper overlay on cigar CTP');
assert.match(route, /VERCEL_ENV !== 'preview'/);
assert.ok(!ui.includes('/api/assessment/submit'), 'Existing core CTP unchanged');
const email=fs.readFileSync(path.join(root,'lib/cigar-ctp/report-email.ts'),'utf8');
assert.match(email,/ea-logo\.png/);
assert.match(email,/Book Your Strategy Meeting/);
const live=fs.readFileSync(path.join(root,'app/api/cigar-ctp/submit/route.ts'),'utf8');
assert.match(live,/CIGAR_CTP_LIVE_SUBMISSIONS_ENABLED/);
assert.match(live,/Email Status/);
console.log('PASS: 30 cigar questions, role branching, per-question editorial explanations, 35 contextual photos, dynamic title, readable motto, scroll, removed filler, and submission/email guardrails');