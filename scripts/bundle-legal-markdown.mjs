#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = [
  'privacy-v1.0.md',
  'terms-v1.0.md',
  'eula-v1.0.md',
  'ai-disclosure-v1.0.md',
  'support-policy-v1.0.md',
  'cookie-policy-v1.0.md',
  'msa-v1.0.md',
  'sow-template-v1.0.md',
];

const entries = files.map((f) => {
  const rel = `docs/legal/${f}`;
  const body = readFileSync(join(root, rel), 'utf8');
  return `  ${JSON.stringify(rel)}: ${JSON.stringify(body)}`;
});

const out = `/**
 * Bundled Legal Pack Markdown for Vercel serverless.
 * Regenerated by scripts/bundle-legal-markdown.mjs — do not hand-edit.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const BUNDLE: Record<string, string> = {
${entries.join(',\n')}
};

export function loadLegalMarkdown(sourcePath: string): string {
  try {
    const abs = join(process.cwd(), sourcePath);
    if (existsSync(abs)) return readFileSync(abs, 'utf8');
  } catch {
    // use bundle
  }
  const bundled = BUNDLE[sourcePath];
  if (!bundled) throw new Error('Legal source missing: ' + sourcePath);
  return bundled;
}
`;

writeFileSync(join(root, 'lib/legal/load-legal-source.ts'), out);
console.log('OK: bundled', files.length, 'legal sources');
